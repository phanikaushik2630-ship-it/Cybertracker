@app.get(
    "/health",
    response_model=HealthResponse,
    summary="Health Check",
    tags=["Monitoring"],
)
async def health_check() -> HealthResponse:
    """
    Returns the current operational status of the API.

    Use this endpoint to:
    - Verify the server is running
    - Check whether the Gemini API key is configured
    - Check whether ML models are loaded
    """
    return HealthResponse(
        status="ok",
        gemini_available=app_state.gemini_available,
        ml_models_active=USE_ML_MODELS,
        model=GEMINI_MODEL,
        version=app.version,
    )


@app.post(
    "/check-message",
    response_model=CheckMessageResponse,
    summary="Analyse a message or URL for fraud risk",
    tags=["Detection"],
    responses={
        200: {"description": "Successful fraud analysis"},
        422: {"description": "Validation error — bad request body"},
        500: {"description": "Internal server error"},
        503: {"description": "Detection engine not ready"},
    },
)
async def check_message(payload: CheckMessageRequest) -> CheckMessageResponse:
    """
    Full fraud detection pipeline in one call:

    1. **Rule Engine** — regex patterns, keyword matching, sender anomaly checks
    2. **ML Classifiers** — SMS Naive Bayes + URL Logistic Regression (if trained)
    3. **Gemini Explanation** — translates signals into plain-language verdict
    4. Returns a structured JSON response

    The `sender` field is optional but enables additional checks against
    TRAI DLT header formats — useful for validating Indian commercial SMS.
    """
    # Guard: scorer must be initialised (should always be true after startup)
    if app_state.scorer is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Detection engine is not ready. Please retry in a moment.",
        )

    t_start = time.perf_counter()

    # ------------------------------------------------------------------
    # Step 1: Run the fraud detection engine
    # ------------------------------------------------------------------
    try:
        breakdown = app_state.scorer.score(
            text=payload.message,
            sender=payload.sender or "",
        )
    except Exception as exc:
        logger.error(f"Scorer error: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Detection engine error: {str(exc)}",
        )

    # ------------------------------------------------------------------
    # Step 2: Build the Gemini prompt from the ScoreBreakdown
    # ------------------------------------------------------------------
    prompt_payload = build_claude_prompt(
        breakdown=breakdown,
        raw_message=payload.message,
        preview_length=200,
    )

    # ------------------------------------------------------------------
    # Step 3: Call Gemini (or fall back to the deterministic mock)
    # ------------------------------------------------------------------
    gemini_used = False

    if app_state.gemini_available:
        try:
            raw_gemini_response = call_gemini(prompt_payload["user"])
            explanation = parse_claude_response(raw_gemini_response)
            gemini_used = True
            logger.info(
                f"Gemini responded | score={breakdown.final_score:.1f} "
                f"verdict={explanation.verdict}"
            )
        except RuntimeError as exc:
            # Gemini call failed — fall back gracefully, do not crash the request
            logger.warning(f"Gemini unavailable, using mock fallback. Reason: {exc}")
            explanation = mock_claude_response(breakdown)
    else:
        # No API key configured — use rule-template mock
        explanation = mock_claude_response(breakdown)

    t_end = time.perf_counter()
    processing_ms = round((t_end - t_start) * 1000, 2)

    # ------------------------------------------------------------------
    # Step 4: Assemble and return the response
    # ------------------------------------------------------------------
    return CheckMessageResponse(
        # Gemini / mock explanation
        verdict=explanation.verdict,
        explanation=explanation.explanation,
        action=explanation.action,

        # Detection engine signals
        risk_score=breakdown.final_score,
        risk_label=breakdown.risk_label,
        signals=breakdown.triggered_rules,
        detected_urls=breakdown.detected_urls,

        # Score breakdown details
        score_breakdown=ScoreBreakdownResponse(
            rule_score=breakdown.rule_score,
            sms_ml_score=breakdown.sms_ml_score,
            url_ml_score=breakdown.url_ml_score,
            ml_active=breakdown.ml_available,
        ),

        # Meta
        gemini_used=gemini_used,
        processing_time_ms=processing_ms,
    )


# ---------------------------------------------------------------------------
# Global Exception Handler — catch anything that slips through
# ---------------------------------------------------------------------------

@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """
    Catch-all handler to ensure every unhandled error returns a clean
    JSON response instead of a raw 500 traceback.
    """
    logger.error(f"Unhandled exception on {request.url}: {exc}", exc_info=True)
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content={
            "error": "internal_server_error",
            "detail": "An unexpected error occurred. Please try again.",
        },
    )


