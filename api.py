"""
api.py — CyberTrack FastAPI Backend
=====================================
Single-file FastAPI application exposing two endpoints:

  POST /check-message   → Full fraud analysis + Gemini explanation
  GET  /health          → Service health check

ARCHITECTURE:
  Request (text + optional sender)
      │
      ▼
  FraudScorer (rule engine + optional ML models)
      │  ScoreBreakdown
      ▼
  GeminiExplainer (builds prompt → calls gemini-1.5-flash → parses response)
      │  FraudExplanation
      ▼
  JSON Response { verdict, explanation, action, score, signals, ... }

CONFIGURATION:
  Set GOOGLE_API_KEY in a .env file (see .env.example).
  Never hardcode the API key.

RUN:
  uvicorn api:app --reload --port 8000

API DOCS (auto-generated by FastAPI):
  http://localhost:8000/docs
"""

import logging
import os
import time
from contextlib import asynccontextmanager
from typing import Optional

from google import genai
from google.genai import types as genai_types
from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException, Request, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse, RedirectResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field, field_validator

from fraud_detector import FraudScorer
from fraud_detector.claude_explainer import (
    SYSTEM_PROMPT,
    build_claude_prompt,
    mock_claude_response,
    parse_claude_response,
)

# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s — %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("cybertrack.api")

# ---------------------------------------------------------------------------
# Load environment variables from .env BEFORE anything else
# ---------------------------------------------------------------------------

load_dotenv()  # Reads .env in the project root into os.environ

GOOGLE_API_KEY = os.getenv("GOOGLE_API_KEY")
GEMINI_MODEL   = os.getenv("GEMINI_MODEL", "gemini-2.0-flash")
USE_ML_MODELS  = os.getenv("USE_ML_MODELS", "false").lower() == "true"


# ---------------------------------------------------------------------------
# App-level shared state (initialised once at startup via lifespan)
# ---------------------------------------------------------------------------

class AppState:
    """
    Holds singleton objects that are expensive to create.
    Initialised once at startup, reused on every request.
    """
    scorer: FraudScorer = None
    gemini_model: genai.GenerativeModel = None
    gemini_available: bool = False


app_state = AppState()


# ---------------------------------------------------------------------------
# Lifespan: startup + shutdown hooks (FastAPI recommended pattern)
# ---------------------------------------------------------------------------

@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Code before `yield` runs at startup; code after runs at shutdown.
    This replaces the deprecated @app.on_event("startup") decorator.
    """
    # -- Startup --
    logger.info("Starting CyberTrack API...")

    # 1. Initialise the fraud scorer (loads ML models if USE_ML_MODELS=true)
    app_state.scorer = FraudScorer(use_ml=USE_ML_MODELS)
    logger.info(f"FraudScorer ready (ML models: {USE_ML_MODELS})")

    # 2. Initialise Gemini client
    if not GOOGLE_API_KEY:
        logger.warning(
            "GOOGLE_API_KEY not set in environment. "
            "Gemini explanations will use the offline mock fallback."
        )
        app_state.gemini_available = False
    else:
        try:
            # Initialise the new google-genai client
            app_state.gemini_model = genai.Client(api_key=GOOGLE_API_KEY)
            # Quick connectivity test
            _ = app_state.gemini_model.models.list()
            app_state.gemini_available = True
            logger.info(f"Gemini model '{GEMINI_MODEL}' initialised successfully.")
        except Exception as exc:
            logger.error(f"Gemini initialisation failed: {exc}")
            app_state.gemini_available = False

    logger.info("CyberTrack API is ready.")
    yield

    # -- Shutdown --
    logger.info("CyberTrack API shutting down.")


# ---------------------------------------------------------------------------
# FastAPI Application
# ---------------------------------------------------------------------------

app = FastAPI(
    title="CyberTrack — SMS & Phishing Fraud Detection API",
    description=(
        "Scores text messages and URLs for fraud risk using a hybrid "
        "rule-based + ML engine, then generates a plain-language "
        "explanation via Google Gemini."
    ),
    version="1.0.0",
    lifespan=lifespan,
    docs_url="/docs",
    redoc_url="/redoc",
)

# Serve the HTML frontend from the static/ directory.
# The UI is reachable at http://localhost:8000/
# API endpoints (/check-message, /health, /docs) take priority over static files.
app.mount("/static", StaticFiles(directory="static"), name="static")

# Allow cross-origin requests (useful when connecting a React/HTML frontend)
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],      # Restrict to specific origins in production
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)


@app.get("/", include_in_schema=False)
async def root():
    """Redirect bare root URL to the static HTML UI."""
    return RedirectResponse(url="/static/index.html")


# ---------------------------------------------------------------------------
# Request / Response Pydantic Models
# ---------------------------------------------------------------------------

class CheckMessageRequest(BaseModel):
    """
    Input payload for POST /check-message.

    Fields:
        message: The raw SMS text or URL string to analyse. Required.
        sender:  Optional sender ID or phone number (enables sender anomaly
                 checks, e.g. TRAI DLT header validation).
    """
    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="The SMS message text or URL to analyse for fraud.",
        examples=["URGENT: Your Aadhaar KYC expired! Click http://uidai-kyc.xyz now"],
    )
    sender: Optional[str] = Field(
        default="",
        max_length=50,
        description="Optional SMS sender ID or phone number (e.g. 'VM-SBIBNK' or '+917900...').",
        examples=["VM-HDFCBK"],
    )

    @field_validator("message")
    @classmethod
    def message_must_not_be_blank(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("message must not be empty or whitespace only")
        return v.strip()


class ScoreBreakdownResponse(BaseModel):
    """Detailed breakdown of how the risk score was computed."""
    rule_score: float   = Field(description="Rule engine contribution (0–100)")
    sms_ml_score: float = Field(description="SMS classifier contribution (0–100)")
    url_ml_score: float = Field(description="URL classifier contribution (0–100)")
    ml_active: bool     = Field(description="Whether trained ML models were used")


class CheckMessageResponse(BaseModel):
    """
    Full response payload for POST /check-message.

    The top-level fields (verdict, explanation, action) are the
    Gemini-generated human-readable output.
    The risk_score and signals fields come directly from the detection engine.
    """
    # Gemini-generated explanation
    verdict: str     = Field(description="Safe | Suspicious | High Risk")
    explanation: str = Field(description="2–3 plain-language sentences for the user")
    action: str      = Field(description="One recommended action for the user")

    # Detection engine output
    risk_score: float                   = Field(description="Combined risk score 0–100")
    risk_label: str                     = Field(description="Human-readable risk tier")
    signals: list[str]                  = Field(description="List of triggered rule names")
    detected_urls: list[str]            = Field(description="URLs found in the message")
    score_breakdown: ScoreBreakdownResponse

    # Meta
    gemini_used: bool = Field(description="True if Gemini API was called; False if mock was used")
    processing_time_ms: float = Field(description="Total server-side processing time in ms")


class HealthResponse(BaseModel):
    """Response for GET /health."""
    status: str
    gemini_available: bool
    ml_models_active: bool
    model: str
    version: str


class ErrorResponse(BaseModel):
    """Standardised error payload."""
    error: str
    detail: str


# ---------------------------------------------------------------------------
# Gemini Explainer Helper
# ---------------------------------------------------------------------------

def call_gemini(prompt_user: str) -> str:
    """
    Send the user-turn prompt to Gemini and return the raw text response.

    Uses the new google-genai SDK (google.genai.Client).
    The system instruction is prepended to the user message since the new
    SDK's generate_content accepts it via the `config` parameter.

    Args:
        prompt_user: The formatted user-turn prompt string from build_claude_prompt().

    Returns:
        Raw text content of Gemini's response.

    Raises:
        RuntimeError: On API errors (network, quota, safety filter, etc.)
    """
    try:
        response = app_state.gemini_model.models.generate_content(
            model=GEMINI_MODEL,
            contents=prompt_user,
            config=genai_types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT,
                temperature=0.2,
                max_output_tokens=300,
            ),
        )
        return response.text
    except Exception as exc:
        raise RuntimeError(f"Gemini API call failed: {exc}") from exc


